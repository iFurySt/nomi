import type { CanvasConnector, CanvasHead, CanvasPoint } from "./document";
import { canvasConnectorGeometry, type CanvasRect } from "./geometry";

type Segment = CanvasPoint[];
const lerp = (a: CanvasPoint, b: CanvasPoint, t: number): CanvasPoint => ({
  x: a.x + (b.x - a.x) * t,
  y: a.y + (b.y - a.y) * t,
});
function split(segment: Segment, t: number): [Segment, Segment] {
  let row = segment;
  const left = [row[0]],
    right = [row.at(-1)!];
  while (row.length > 1) {
    row = row.slice(1).map((p, i) => lerp(row[i], p, t));
    left.push(row[0]);
    right.unshift(row.at(-1)!);
  }
  return [left, right];
}
function length(segment: Segment, depth = 0): number {
  const chord = Math.hypot(
    segment.at(-1)!.x - segment[0].x,
    segment.at(-1)!.y - segment[0].y,
  );
  const polygon = segment
    .slice(1)
    .reduce(
      (n, p, i) => n + Math.hypot(p.x - segment[i].x, p.y - segment[i].y),
      0,
    );
  if (depth === 12 || polygon - chord < 0.002) return (polygon + chord) / 2;
  const [a, b] = split(segment, 0.5);
  return length(a, depth + 1) + length(b, depth + 1);
}
/** Only consumes the absolute M/L/Q/C paths generated by the canvas kernel. */
function segments(d: string): Segment[] {
  const tokens =
    d.match(/[MLQC]|[-+]?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?/gi) ?? [];
  const result: Segment[] = [];
  let i = 0,
    point: CanvasPoint = { x: 0, y: 0 };
  while (i < tokens.length) {
    const op = tokens[i++],
      count =
        op === "M" || op === "L" ? 1 : op === "Q" ? 2 : op === "C" ? 3 : 0;
    if (!count) throw Error("Unsupported generated canvas path");
    const next: Segment = [point];
    for (let j = 0; j < count; j++)
      next.push({ x: Number(tokens[i++]), y: Number(tokens[i++]) });
    if (next.some((p) => !Number.isFinite(p.x) || !Number.isFinite(p.y)))
      throw Error("Invalid generated canvas path");
    point = next.at(-1)!;
    if (op !== "M") result.push(next);
  }
  return result;
}
function trimStart(path: Segment[], inset: number): Segment[] {
  while (path.length && inset > 1e-8) {
    const size = length(path[0]);
    if (inset >= size && path.length > 1) {
      inset -= size;
      path = path.slice(1);
      continue;
    }
    if (path[0].length === 2) {
      path = [split(path[0], Math.min(1, inset / size))[1], ...path.slice(1)];
      break;
    }
    let low = 0,
      high = 1;
    for (let i = 0; i < 28; i++) {
      const mid = (low + high) / 2;
      if (length(split(path[0], mid)[0]) < inset) low = mid;
      else high = mid;
    }
    path = [split(path[0], (low + high) / 2)[1], ...path.slice(1)];
    break;
  }
  return path;
}
/** Trim ink by arc length, retaining the exact quadratic/cubic subcurves.
 * Very short connectors keep at least 20% of their path instead of inverting. */
export function trimCanvasPath(d: string, start: number, end: number): string {
  if (!start && !end) return d;
  let path = segments(d);
  if (!path.length) return d;
  const total = path.reduce((n, s) => n + length(s), 0);
  if (total < 1e-8) return d;
  const scale = Math.min(1, (total * 0.8) / (start + end));
  path = trimStart(path, start * scale);
  path = trimStart(
    [...path].reverse().map((s) => [...s].reverse()),
    end * scale,
  )
    .reverse()
    .map((s) => [...s].reverse());
  const p = path[0][0];
  return (
    `M ${p.x} ${p.y}` +
    path
      .map(
        (s) =>
          ` ${s.length === 2 ? "L" : s.length === 3 ? "Q" : "C"} ` +
          s
            .slice(1)
            .map((p) => `${p.x} ${p.y}`)
            .join(" "),
      )
      .join("")
  );
}
/** Align the marker's front centerline with the shaft endpoint. Both use the
 * same effective stroke width and round cap/join; adding a stroke radius here
 * moves the head backwards and leaves the shaft poking through the arrow tip. */
export function canvasHeadRefX(head: CanvasHead): number {
  return head === "triangle" ||
    head === "triangle-open" ||
    head === "crowfoot-circle"
    ? 13
    : head === "bar"
      ? 11
      : 12;
}
export function canvasConnectorPaintGeometry(
  c: CanvasConnector,
  rectangles: CanvasRect[],
  zoom = 1,
) {
  const logical = canvasConnectorGeometry(c, rectangles);
  if (!logical) return null;
  const inset = (end: "from" | "to") => {
    const r = rectangles.find((r) => r.id === c[end].placement);
    if (!r) return 0;
    const border = r.shape
      ? r.shape === "text" || r.shapeStyle?.strokeOpacity === 0
        ? 0
        : (r.shapeStyle?.strokeWidth ?? 1.25)
      : 1;
    return (3 + border / 2 + (c.width ?? 2) / 2) / zoom;
  };
  return {
    ...logical,
    d: trimCanvasPath(logical.d, inset("from"), inset("to")),
  };
}
