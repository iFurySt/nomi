import { build } from "esbuild";
import { mkdir, readFile, writeFile, copyFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repo = fileURLToPath(new URL("../", import.meta.url));
const skill = path.join(repo, "skills/nomi-interactive");
await mkdir(path.join(skill, "scripts"), { recursive: true });
// Ship the real parser/evaluator so an external agent needs only Node, not this checkout.
await build({
  stdin: {
    contents: `export { parseInteractiveProgram, validateResolvedProps } from './packages/core/src/interactive/validate';
export { evaluateProgram, hydrateStudyState, setStudyValue, runStudyAction } from './packages/core/src/interactive/runtime';`,
    resolveDir: repo,
    loader: "ts",
  },
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  outfile: path.join(skill, "scripts/runtime.mjs"),
  banner: {
    js: "// Generated by scripts/build-interactive-skill.mjs from Nomi core. AGPL-3.0-only.",
  },
});
const prompt = await readFile(
  path.join(repo, "packages/host/src/canvas-generation-prompt.ts"),
  "utf8",
);
const contract = prompt
  .split("const interactiveContract = `\n")[1]
  ?.split("\nStreaming:")[0];
if (!contract)
  throw new Error(
    "Interactive contract boundary changed; update skill builder.",
  );
await writeFile(
  path.join(skill, "references/contract.md"),
  "# Portable contract snapshot\n\nGenerated from Nomi's generation contract. Snapshot: 2026-11-11. UI design refinements and unsupported preview features are documented in design.md.\n\n" +
    contract +
    "\n",
);
for (const name of ["wave", "temperature"])
  await copyFile(
    path.join(repo, `packages/core/src/interactive/${name}.json`),
    path.join(skill, `assets/${name}.nomi-ui.json`),
  );

const p = JSON.parse(
  await readFile(
    path.join(repo, "packages/core/src/interactive/bpe.json"),
    "utf8",
  ),
);
p.id = "bpe-compact";
const literal = (value) => ({ kind: "literal", value });
const call = (fn, ...args) => ({
  kind: "call",
  function: fn,
  version: 1,
  args,
});
const field = (name) =>
  call("object.get", { kind: "derived", id: "training" }, literal(name));
const formatted = (name) => call("number.format", field(name), literal(0));
const concat = (...parts) =>
  parts.reduce((a, b) => call("string.concat", a, b));
const remove = new Set(["intro", "before", "after", "round"]);
p.nodes = p.nodes.filter((n) => !remove.has(n.id));
p.nodes.find((n) => n.id === "root").props.children = [
  "heading",
  "corpus",
  "controls",
  "metrics",
  "process",
  "results",
];
p.nodes.find((n) => n.id === "heading").props.text = "BPE 分词";
p.nodes.find((n) => n.id === "corpus").props.label = "句子";
const summary = p.nodes.find((n) => n.id === "metrics");
summary.component = "Text";
summary.props = {
  text: concat(
    literal("词元 "),
    formatted("initialTokens"),
    literal(" → "),
    formatted("tokenCount"),
    literal(" · 第 "),
    formatted("step"),
    literal(" 轮"),
  ),
};
p.nodes.find((n) => n.id === "next").props.label = "合并一步";
p.nodes.find((n) => n.id === "words").props.caption = "当前拆分";
p.nodes.find((n) => n.id === "pairs").props.caption = "候选合并 · 首行优先";
p.nodes.find((n) => n.id === "vocabulary").props.caption = "词表";
delete p.requires.components.Metric;
p.requires.functions["number.format"] = 1;
p.requires.functions["string.concat"] = 1;
// Versioned, platform-neutral presentation capabilities.
p.version = 2;
for (const kind of ["Table", "Button", "TextInput"]) {
  p.requires.components[kind] = 2;
  for (const n of p.nodes.filter((n) => n.component === kind)) n.version = 2;
}
const node = (id) => p.nodes.find((n) => n.id === id);
node("corpus").props.resetTargets = ["step"];
node("controls").props.children = ["metrics", "prev", "reset", "next"];
node("root").props.children = [
  "heading",
  "corpus",
  "controls",
  "process",
  "results",
];
node("prev").props.icon = "previous";
node("reset").props.icon = "restart";
node("reset").props.label = "重新开始";
node("next").props = {
  label: field("nextLabel"),
  variant: "primary",
  disabled: field("complete"),
};
node("prev").props.disabled = field("atStart");
node("corpus").props.hideLabel = true;
node("reset").props.disabled = field("atStart");
node("metrics").props.text = field("tokenLabel");
p.nodes.push({
  id: "roundLabel",
  component: "Text",
  version: 1,
  props: { text: concat(literal("第 "), formatted("step"), literal(" 轮")) },
});
p.nodes.push({
  id: "headingRow",
  component: "Row",
  version: 1,
  props: { children: ["heading", "roundLabel"] },
});
node("root").props.children[0] = "headingRow";
node("words").props = {
  columns: ["词", "次数", "词元"],
  rows: field("segmentationRows"),
  caption: "当前拆分",
  hint: "▁ 词尾",
  showCount: false,
  columnAlign: ["left", "right", "left"],
};
node("pairs").props = {
  columns: ["相邻词元", "频次", "下一步"],
  rows: field("candidateRows"),
  caption: "候选合并",
  hint: "按频次",
  showCount: false,
  emptyText: field("candidateEmpty"),
  highlightRow: field("nextPairIndex"),
  columnAlign: ["left", "right", "right"],
};
node("merges").props = {
  columns: ["轮", "规则", "频次"],
  rows: field("ruleRows"),
  caption: "合并规则",
  hint: "执行顺序",
  emptyText: "尚未合并",
  columnAlign: ["left", "left", "right"],
};
node("vocabulary").props = {
  columns: ["ID", "词元", "当前频次"],
  rows: field("vocabularyRows"),
  caption: "词表",
  hint: "全部已学",
  columnAlign: ["left", "left", "right"],
};
for (const n of p.nodes.filter((n) => n.component === "Table")) {
  n.props.visibleRows = 6;
  n.props.window =
    n.id === "vocabulary"
      ? field("vocabularyWindow")
      : n.id === "merges"
        ? "end"
        : "start";
}
await writeFile(
  path.join(repo, "packages/core/src/interactive/bpe-compact.json"),
  JSON.stringify(p, null, 2) + "\n",
);
await writeFile(
  path.join(skill, "assets/bpe-compact.nomi-ui.json"),
  JSON.stringify(p, null, 2) + "\n",
);
await copyFile(path.join(repo, "LICENSE"), path.join(skill, "LICENSE"));
console.log("Updated portable skill runtime, contract and examples.");
